drop policy if exists deny_salary_slips_api on public.salary_slips;
create policy deny_salary_slips_api on public.salary_slips for all to anon, authenticated using (false) with check (false);
drop policy if exists deny_salary_holds_api on public.salary_holds;
create policy deny_salary_holds_api on public.salary_holds for all to anon, authenticated using (false) with check (false);
